# Vetor: é mutável, ordenado e indexado (0..n)
a = [10,20,30]

# Tupla: imutável, ordenada e indexada (0..n)
b = (10,20,30)

# Dicionário: mutável, é ordenado a partir da v3.7, acesso pela chave
c = {"num1": 10, "num2": 20, "num3": 30}

# Matriz
d = [[10,20,30]]

print(type(a))
print(type(b))
print(type(c))
print(type(d))